-- media-service | PostgreSQL | DB: music4_media
CREATE TABLE media_files (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key        VARCHAR(500) NOT NULL,
    original_filename VARCHAR(255),
    content_type      VARCHAR(255),
    media_type        VARCHAR(50)  NOT NULL CHECK (media_type IN ('IMAGE', 'AUDIO')),
    file_size         BIGINT,
    bucket_name       VARCHAR(255) NOT NULL,
    duration          INTEGER,
    uploaded_by       INTEGER,
    created_at        TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT uq_media_files_object_key UNIQUE (object_key)
);
CREATE INDEX ix_media_files_type ON media_files (media_type, id DESC);
