-- user-service | PostgreSQL | DB: music4_user
CREATE TABLE users (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    img         TEXT,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL,
    password    VARCHAR(255) NOT NULL,               -- luôn là BCrypt hash
    user_name   VARCHAR(50)  NOT NULL,
    role        VARCHAR(20)  NOT NULL DEFAULT 'LISTENER',
    artist_id   INTEGER,                             -- id hồ sơ bên content-service (không FK chéo DB)
    gender      BOOLEAN,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_user_name UNIQUE (user_name),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('LISTENER', 'ARTIST', 'ADMIN'))
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(255) NOT NULL,
    username    VARCHAR(255) NOT NULL,
    source      VARCHAR(255) NOT NULL,
    expiry_date TIMESTAMP(6) NOT NULL,
    revoked     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_refresh_tokens_token UNIQUE (token)
);
CREATE INDEX ix_refresh_tokens_username ON refresh_tokens (username);

CREATE TABLE password_reset_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token        VARCHAR(255) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    account_type VARCHAR(255) NOT NULL,
    expiry_date  TIMESTAMP(6) NOT NULL,
    used         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_password_reset_tokens_token UNIQUE (token)
);
